/** The Storybook fixture generator: what it writes, and that it refuses to write a guess. */
import { describe, it } from 'node:test';
import { strict as assert } from 'node:assert';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { generateFixtures, renderFixtureModule } from './generate-voted-resolved-fixtures.js';
import { votedResolvedFixtures } from '../src/components/social-cards/votedResolvedFixtures.js';
import { DEFAULT_REAL_VOTE } from '../src/components/social-cards/votedRealVoteDefaults.js';
import { resolveLegislatorVoteViewFromFiles } from '../src/utils/resolveLegislatorVoteViewFromFiles.js';
import { toVotedCardProps } from '../src/utils/legislatorVoteView.js';

const out = () => path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'vfu-fixture-')), 'votedResolvedFixtures.ts');

describe('renderFixtureModule', () => {
  const source = renderFixtureModule({ sandersSjres3Nay: votedResolvedFixtures.sandersSjres3Nay });

  it('is a module that types its own export', () => {
    assert.match(source, /^\/\/ Generated by: /);
    assert.match(source, /import type \{ VotedCardProps \} from '\.\.\/\.\.\/types\/votedCard\.js';/);
    assert.match(source, /export const votedResolvedFixtures = \{/);
    assert.match(source, /as const satisfies Record<string, VotedCardProps>;\n$/);
  });

  it('carries the props as readable JSON', () => {
    assert.match(source, /"sandersSjres3Nay": \{\n {4}"nameTitle": "Sen\. Bernard Sanders \(VT\)"/);
  });
});

describe('generateFixtures', () => {
  it('resolves the default real vote and writes its card props', async () => {
    const file = out();
    let asked: unknown;
    const written = await generateFixtures({
      out: file,
      resolve: async (params) => { asked = params; return resolveLegislatorVoteViewFromFiles(params); },
    });
    assert.equal(written, file);
    assert.deepEqual(asked, DEFAULT_REAL_VOTE);
    const result = await resolveLegislatorVoteViewFromFiles(DEFAULT_REAL_VOTE);
    assert.ok(result.ok);
    assert.equal(fs.readFileSync(file, 'utf8'), renderFixtureModule({ sandersSjres3Nay: toVotedCardProps(result.view) }));
  });

  it('throws, and writes nothing, when the vote is not in the data', async () => {
    const file = out();
    await assert.rejects(
      generateFixtures({ out: file, resolve: async () => ({ ok: false, reason: 'vote-not-found' }) }),
      /Fixture generation failed: vote-not-found/,
    );
    assert.equal(fs.existsSync(file), false);
  });
});
