/**
 * Regenerates `votedResolvedFixtures` (the Storybook card built from real
 * data) from on-disk bill and legislator JSON.
 *
 * ```bash
 * npx tsx scripts/generate-voted-resolved-fixtures.ts
 * ```
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_REAL_VOTE } from '../src/components/social-cards/votedRealVoteDefaults.js';
import { toVotedCardProps, type ResolveLegislatorVoteResult } from '../src/utils/legislatorVoteView.js';
import { resolveLegislatorVoteViewFromFiles } from '../src/utils/resolveLegislatorVoteViewFromFiles.js';
import type { VotedCardProps } from '../src/types/votedCard.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/components/social-cards/votedResolvedFixtures.ts');

/**
 * The fixture module's source.
 *
 * @param fixtures - Card props by fixture name
 * @returns TypeScript source for `votedResolvedFixtures.ts`
 */
export function renderFixtureModule(fixtures: Record<string, VotedCardProps>): string {
  return `// Generated by: node --import tsx scripts/generate-voted-resolved-fixtures.ts
// Do not edit by hand.

import type { VotedCardProps } from '../../types/votedCard.js';

export const votedResolvedFixtures = ${JSON.stringify(fixtures, null, 2)} as const satisfies Record<string, VotedCardProps>;
`;
}

/**
 * Resolve the default real vote and write the fixture module.
 *
 * @param options.out - File to write
 * @param options.resolve - Resolver; the on-disk one unless a test supplies its own
 * @returns The path written
 * @throws When the vote or the member is not in the data
 */
export async function generateFixtures(options: {
  out?: string;
  resolve?: (params: { voteId: string; bioguideId: string }) => Promise<ResolveLegislatorVoteResult>;
} = {}): Promise<string> {
  const out = options.out ?? OUT;
  const result = await (options.resolve ?? resolveLegislatorVoteViewFromFiles)(DEFAULT_REAL_VOTE);
  if (!result.ok) throw new Error(`Fixture generation failed: ${result.reason}`);
  writeFileSync(out, renderFixtureModule({ sandersSjres3Nay: toVotedCardProps(result.view) }));
  return out;
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  generateFixtures()
    .then((out) => console.log(`Wrote ${out}`))
    .catch((err: unknown) => {
      console.error(err instanceof Error ? err.message : err);
      process.exit(1);
    });
}
